// Deterministic Supplier Prices Generator:
// Price is generated ONLY for ingredients that the supplier carries.
export function generateSupplierPrices(): SupplierPrice[] {
  const prices: SupplierPrice[] = [];
  const suppliers = SUPPLIERS;

  INGREDIENTS.forEach((ing) => {
    suppliers.forEach((sup) => {
      // Check if supplier sells this ingredient category
      const sellsCategory =
        sup.categoriesSold?.some((c) => ing.category.toLowerCase().includes(c.toLowerCase())) ||
        sup.categoriesSold?.includes('All');

      if (!sellsCategory) return; // Leave empty if outside category

      let multiplier = 1.0;
      if (sup.type === 'mandi') multiplier = 1.0; // Best mandi baseline
      else if (sup.type === 'wholesaler') multiplier = 1.07;
      else if (sup.type === 'b2b_platform') multiplier = 1.14;
      else multiplier = 1.25; // Retail supermarket

      const rawRate = Math.round(ing.bestCityPrice * multiplier);

      prices.push({
        id: `sp-${ing.id}-${sup.id}`,
        supplierId: sup.id,
        supplierName: sup.name,
        supplierType: sup.type,
        ingredientId: ing.id,
        cityId: sup.cityId,
        price: rawRate,
        unit: ing.standardUnit,
        moq: sup.minOrderQty || 5,
        deliveryDays: sup.deliveryTime || 'Same-day morning',
        qualityScore: sup.type === 'mandi' ? 98 : sup.rating >= 4.8 ? 95 : 90,
        updatedDate: 'Today 5:30 AM',
        isBestPrice: multiplier <= 1.01,
      });
    });
  });

  return prices;
}

