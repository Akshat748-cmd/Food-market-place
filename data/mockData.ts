// Helper to define ingredients concisely
function makeIng(
  id: string,
  name: string,
  category: any,
  standardUnit: any,
  currentAvgPrice: number,
  bestCityPrice: number,
  monthlyUsageQuantity: number,
  tags: string[] = ['Mandi Grade']
): Ingredient {
  const savings = Math.max(0, (currentAvgPrice - bestCityPrice) * monthlyUsageQuantity);
  return {
    id,
    name,
    category,
    standardUnit,
    currentAvgPrice,
    userCurrentPrice: currentAvgPrice, // Default: owner pays retail/market rate today
    bestCityPrice,
    bestSupplierId: 'sup-delhi-02',
    bestSupplierName: 'Verka Mandi Dairy Wholesaler',
    monthlyUsageQuantity,
    potentialSavingsMonthly: savings,
    qualityGrade: 'A+',
    tags,
  };
}

